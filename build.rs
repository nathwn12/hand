//! Build-time provenance stamp plus embedded skill files.

use std::process::Command;

fn main() {
    println!("cargo:rerun-if-changed=.git/HEAD");
    println!("cargo:rerun-if-changed=.git/index");
    if let Some(reference) = git(&["symbolic-ref", "-q", "HEAD"]) {
        println!("cargo:rerun-if-changed=.git/{reference}");
    }
    println!("cargo:rerun-if-changed=.git/logs/HEAD");
    println!("cargo:rerun-if-changed=.git/packed-refs");
    println!("cargo:rerun-if-changed=src");
    println!("cargo:rerun-if-changed=crates");
    println!("cargo:rerun-if-changed=skills");

    let sha = git(&["rev-parse", "HEAD"]).unwrap_or_else(|| "unknown".to_string());
    let dirty =
        git(&["status", "--porcelain", "--untracked-files=no"]).is_some_and(|s| !s.is_empty());
    let profile = std::env::var("PROFILE").unwrap_or_else(|_| "unknown".to_string());

    println!("cargo:rustc-env=HAND_GIT_SHA={sha}");
    println!("cargo:rustc-env=HAND_GIT_DIRTY={}", u8::from(dirty));
    println!("cargo:rustc-env=HAND_BUILD_PROFILE={profile}");

    generate_skills();
}

fn git(args: &[&str]) -> Option<String> {
    let out = Command::new("git")
        .args(args)
        .current_dir(env!("CARGO_MANIFEST_DIR"))
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    Some(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

fn generate_skills() {
    use sha2::{Digest, Sha256};
    use std::fs;
    use std::path::Path;

    let manifest_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let skills_root = manifest_dir.join("skills");

    let mut files: Vec<(String, String, Vec<u8>)> = Vec::new();
    if skills_root.exists() {
        collect_dir(&skills_root, &skills_root, &mut files);
    }
    files.sort_by(|a, b| (a.0.clone(), a.1.clone()).cmp(&(b.0.clone(), b.1.clone())));

    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
    let out_path = Path::new(&out_dir).join("skills.rs");
    let mut out = String::new();
    out.push_str("// Generated by build.rs - embedded skill files. Do not edit.\n");
    out.push_str("#[derive(Clone, Copy)]\n");
    out.push_str("pub struct SkillFile {\n");
    out.push_str("    pub skill: &'static str,\n");
    out.push_str("    pub rel: &'static str,\n");
    out.push_str("    pub bytes: &'static [u8],\n");
    out.push_str("    pub digest: &'static str,\n");
    out.push_str("    pub size: usize,\n");
    out.push_str("}\n");
    out.push_str("pub static SKILL_FILES: &[SkillFile] = &[\n");
    for (skill, rel, bytes) in &files {
        let mut hasher = Sha256::new();
        hasher.update(bytes);
        let hash = hasher.finalize();
        let mut hex = String::with_capacity(64);
        for b in hash.iter() {
            hex.push_str(&format!("{:02x}", b));
        }
        out.push_str("    SkillFile {\n");
        out.push_str(&format!("        skill: {:?},\n", skill));
        out.push_str(&format!("        rel: {:?},\n", rel));
        out.push_str("        bytes: &[");
        for (i, b) in bytes.iter().enumerate() {
            if i > 0 {
                out.push(',');
            }
            out.push_str(&b.to_string());
        }
        out.push_str("],\n");
        out.push_str(&format!("        digest: \"sha256:{}\",\n", hex));
        out.push_str(&format!("        size: {},\n", bytes.len()));
        out.push_str("    },\n");
    }
    out.push_str("];\n");
    fs::write(&out_path, out).expect("write skills.rs");
}

fn collect_dir(
    root: &std::path::Path,
    dir: &std::path::Path,
    out: &mut Vec<(String, String, Vec<u8>)>,
) {
    let entries = match std::fs::read_dir(dir) {
        Ok(e) => e,
        Err(_) => return,
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            collect_dir(root, &path, out);
        } else if path.is_file() {
            let rel_path = match path.strip_prefix(root) {
                Ok(p) => p,
                Err(_) => continue,
            };
            let mut components = rel_path.components();
            let skill = match components.next() {
                Some(c) => c.as_os_str().to_string_lossy().to_string(),
                None => continue,
            };
            let rest: Vec<String> = components
                .map(|c| c.as_os_str().to_string_lossy().to_string())
                .collect();
            if rest.is_empty() {
                continue;
            }
            let rel = rest.join("/");
            if let Ok(bytes) = std::fs::read(&path) {
                out.push((skill, rel, bytes));
            }
        }
    }
}
